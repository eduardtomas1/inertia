// Embeds the SketchUp extension and AutoCAD bridge in the runtime bundle, which
// must install or run them on machines that have no checkout. Edit the .rb and
// .ps1 files, then run `node scripts/sync-cad-host-sources.mjs`; pass --check
// to fail instead of writing when the generated module is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = new URL("../", import.meta.url);
const HOSTS = "src/server/cad/hosts";
const TARGET = "src/server/cad/bridge-sources.ts";
const SOURCES = [
  ["SKETCHUP_LOADER_RB", `${HOSTS}/sketchup/inertia_cad_bridge.rb`],
  ["SKETCHUP_MAIN_RB", `${HOSTS}/sketchup/inertia_cad_bridge/main.rb`],
  ["AUTOCAD_BRIDGE_PS1", `${HOSTS}/autocad/InertiaCadBridge.ps1`],
];

const read = (path) => readFileSync(new URL(path, ROOT), "utf8").replace(/\r\n/gu, "\n");

function renderHostSources() {
  return [
    "// Generated by scripts/sync-cad-host-sources.mjs. Do not edit.",
    `// Edit the files under ${HOSTS}, then run \`node scripts/sync-cad-host-sources.mjs\`.`,
    ...SOURCES.map(([name, path]) => `export const ${name} = ${JSON.stringify(read(path))};`),
    "",
  ].join("\n");
}

function main() {
  const next = renderHostSources();
  let current = null;
  try {
    current = read(TARGET);
  } catch (error) {
    if (error?.code !== "ENOENT") throw error;
  }
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error(`drift: ${TARGET}`);
      console.error("Run `node scripts/sync-cad-host-sources.mjs` to refresh the embedded CAD host sources.");
      process.exit(1);
    }
    console.log("CAD host sources are current.");
    return;
  }
  if (current === next) {
    console.log("CAD host sources already current.");
    return;
  }
  writeFileSync(new URL(TARGET, ROOT), next);
  console.log(`updated: ${TARGET}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
